package com.example.eventmgmt.service;

import com.example.eventmgmt.aop.Audited;
import com.example.eventmgmt.dto.FileUploadResponse;
import com.example.eventmgmt.entity.Event;
import com.example.eventmgmt.exception.BusinessRuleException;
import com.example.eventmgmt.exception.ResourceNotFoundException;
import com.example.eventmgmt.repository.EventRepository;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.cache.annotation.CacheEvict;
import org.springframework.core.io.Resource;
import org.springframework.core.io.UrlResource;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.multipart.MultipartFile;
import java.io.IOException;
import java.io.InputStream;
import java.net.MalformedURLException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.util.Map;

/** File upload and download: one brochure (PDF / PNG / JPEG) per event. */
@Slf4j
@Service
public class FileStorageService {
    private static final Map<String, String> ALLOWED_TYPES = Map.of(
            "application/pdf", ".pdf",
            "image/png", ".png",
            "image/jpeg", ".jpg");

    private final EventRepository eventRepo;
    private final Path root;

    public FileStorageService(EventRepository eventRepo, @Value("${app.upload-dir:./uploads}") String uploadDir) {
        this.eventRepo = eventRepo;
        this.root = Paths.get(uploadDir).toAbsolutePath().normalize();
        try {
            Files.createDirectories(root);
        } catch (IOException e) {
            throw new IllegalStateException("Cannot create upload directory " + root, e);
        }
    }

    @CacheEvict(value = "events", key = "#eventId")
    @Audited("'Brochure uploaded for event ' + #eventId + ' (' + #result.fileName() + ')'")
    @Transactional(rollbackFor = Exception.class)
    public FileUploadResponse store(Long eventId, MultipartFile file) {
        Event event = eventRepo.findById(eventId)
                .orElseThrow(() -> new ResourceNotFoundException("Event", eventId));
        if (file == null || file.isEmpty())
            throw new BusinessRuleException("Uploaded file is empty");
        String contentType = file.getContentType();
        String extension = contentType == null ? null : ALLOWED_TYPES.get(contentType);
        if (extension == null)
            throw new BusinessRuleException("Only PDF, PNG or JPEG files are allowed");

        // The stored name is generated by the server, never taken from the client (prevents path traversal).
        String storedName = "event-" + eventId + "-brochure" + extension;
        Path target = root.resolve(storedName).normalize();
        if (!target.startsWith(root))
            throw new BusinessRuleException("Invalid file name");

        try {
            String old = event.getBrochureFileName();
            if (old != null) Files.deleteIfExists(root.resolve(old).normalize());
            try (InputStream in = file.getInputStream()) {
                Files.copy(in, target, StandardCopyOption.REPLACE_EXISTING);
            }
        } catch (IOException e) {
            throw new BusinessRuleException("Could not store file: " + e.getMessage());
        }

        event.setBrochureFileName(storedName);
        event.setBrochureContentType(contentType);
        eventRepo.save(event);
        log.info("Stored brochure {} ({} bytes)", storedName, file.getSize());
        return new FileUploadResponse(eventId, storedName, contentType, file.getSize());
    }

    @Transactional(readOnly = true)
    public StoredFile load(Long eventId) {
        Event event = eventRepo.findById(eventId)
                .orElseThrow(() -> new ResourceNotFoundException("Event", eventId));
        if (event.getBrochureFileName() == null)
            throw new ResourceNotFoundException("Brochure for event", eventId);
        Path path = root.resolve(event.getBrochureFileName()).normalize();
        if (!path.startsWith(root) || !Files.exists(path))
            throw new ResourceNotFoundException("Brochure file for event", eventId);
        try {
            Resource resource = new UrlResource(path.toUri());
            return new StoredFile(resource, event.getBrochureFileName(), event.getBrochureContentType());
        } catch (MalformedURLException e) {
            throw new BusinessRuleException("Could not read file: " + e.getMessage());
        }
    }

    public record StoredFile(Resource resource, String fileName, String contentType) {}
}
